#!/usr/bin/env python3
"""Small build-time LR35902 -> C++ static recompiler used by milestone M0.

This deliberately supports only the opcodes needed by the two verified Bank 0
helpers in M0. The next milestone broadens this into the complete LR35902
decoder/control-flow recompiler.
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

DB_LINE = re.compile(r"^\s*db\b", re.IGNORECASE)
BYTE = re.compile(r"\$([0-9A-Fa-f]{2})\b")

EXPECTED = {
    0x0949: bytes.fromhex("57 72 23 0B 78 B1 20 F9 C9"),
    0x1679: bytes.fromhex("1A 13 22 0B 78 B1 20 F8 C9"),
}


@dataclass(frozen=True)
class Instruction:
    pc: int
    opcode: int
    size: int
    target: int | None = None


def load_bank(path: Path) -> bytes:
    out = bytearray()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not DB_LINE.match(line):
            continue
        out.extend(int(m.group(1), 16) for m in BYTE.finditer(line))
    if len(out) != 0x4000:
        raise SystemExit(
            f"{path}: parsed {len(out)} bytes, expected one 16 KiB ROM bank"
        )
    return bytes(out)


def signed8(value: int) -> int:
    return value - 0x100 if value & 0x80 else value


def decode_function(bank: bytes, start: int) -> list[Instruction]:
    pc = start
    out: list[Instruction] = []

    while True:
        opcode = bank[pc]

        if opcode in {0x57, 0x72, 0x23, 0x0B, 0x78, 0xB1,
                      0x1A, 0x13, 0x22, 0xC9}:
            ins = Instruction(pc, opcode, 1)
        elif opcode == 0x20:
            target = pc + 2 + signed8(bank[pc + 1])
            ins = Instruction(pc, opcode, 2, target)
        else:
            raise SystemExit(
                f"unsupported M0 opcode 0x{opcode:02X} at 0x{pc:04X}"
            )

        out.append(ins)
        pc += ins.size

        if opcode == 0xC9:
            return out


def emit_instruction(ins: Instruction) -> list[str]:
    op = ins.opcode

    if op == 0x57:  # LD D,A
        return ["    cpu.d = cpu.a;"]
    if op == 0x72:  # LD (HL),D
        return ["    memory.write8(cpu.hl(), cpu.d);"]
    if op == 0x23:  # INC HL
        return ["    cpu.set_hl(static_cast<std::uint16_t>(cpu.hl() + 1));"]
    if op == 0x0B:  # DEC BC
        return ["    cpu.set_bc(static_cast<std::uint16_t>(cpu.bc() - 1));"]
    if op == 0x78:  # LD A,B
        return ["    cpu.a = cpu.b;"]
    if op == 0xB1:  # OR C
        return ["    cpu.or_a(cpu.c);"]
    if op == 0x1A:  # LD A,(DE)
        return ["    cpu.a = memory.read8(cpu.de());"]
    if op == 0x13:  # INC DE
        return ["    cpu.set_de(static_cast<std::uint16_t>(cpu.de() + 1));"]
    if op == 0x22:  # LD (HL+),A
        return [
            "    memory.write8(cpu.hl(), cpu.a);",
            "    cpu.set_hl(static_cast<std::uint16_t>(cpu.hl() + 1));",
        ]
    if op == 0x20:  # JR NZ,r8
        assert ins.target is not None
        return [f"    if (!cpu.zero()) goto L_{ins.target:04X};"]
    if op == 0xC9:  # RET
        return ["    return;"]

    raise AssertionError(f"unhandled opcode {op:02X}")


def emit_function(name: str, instructions: list[Instruction]) -> str:
    targets = {ins.target for ins in instructions if ins.target is not None}
    lines = [f"void {name}(Cpu& cpu, Memory& memory) {{"]

    for ins in instructions:
        if ins.pc in targets:
            lines.append(f"L_{ins.pc:04X}:")
        lines.extend(emit_instruction(ins))

    lines.append("}")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bank", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    bank = load_bank(args.bank)

    for start, expected in EXPECTED.items():
        actual = bank[start : start + len(expected)]
        if actual != expected:
            raise SystemExit(
                f"verified routine mismatch at 0x{start:04X}: "
                f"{actual.hex(' ')} != {expected.hex(' ')}"
            )

    memset_fn = decode_function(bank, 0x0949)
    memcpy_fn = decode_function(bank, 0x1679)

    cpp = """// AUTO-GENERATED by recomp/tools/recompile_smoke.py.
// Do not edit this file directly.

#include "recomp/generated.hpp"

#include <cstdint>

namespace dwm2t {

"""
    cpp += emit_function("recomp_memset_0949", memset_fn)
    cpp += "\n\n"
    cpp += emit_function("recomp_memcpy_1679", memcpy_fn)
    cpp += "\n\n} // namespace dwm2t\n"

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(cpp, encoding="utf-8", newline="\n")
    print(f"generated {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
